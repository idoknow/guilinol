/** Build compact photo credits from pipeline/landmark-refs.json (+ optional Commons authors cache). */
import {readFileSync, writeFileSync, existsSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const landmarks = JSON.parse(readFileSync(join(root, 'pipeline/landmark-refs.json'), 'utf8'))
const cachePath = join(root, 'pipeline/landmark-authors.json')
const authors = existsSync(cachePath) ? JSON.parse(readFileSync(cachePath, 'utf8')) : {}

function fileTitle(page='') {
  const match = decodeURIComponent(page).match(/\/wiki\/(File:.+)$/i)
  return match ? match[1].replace(/_/g, ' ') : ''
}

const rows = []
for (const landmark of landmarks) {
  if (landmark.viewOnly) continue
  const people = new Set(), licenses = new Set()
  for (const ref of landmark.refs ?? []) {
    if (ref.viewOnly) continue
    if (ref.license) licenses.add(ref.license)
    const name = ref.author || authors[fileTitle(ref.page)] || ''
    if (name) people.add(name)
  }
  if (!people.size && !licenses.size) continue
  rows.push({
    name: landmark.name,
    authors: [...people].sort((a, b) => a.localeCompare(b, 'zh')),
    licenses: [...licenses].sort(),
  })
}

const out = join(root, 'web/src/ui/photo-credits.ts')
writeFileSync(out, `/* Generated by scripts/photo-credits.mjs — do not edit. */\nexport const photoCredits = ${JSON.stringify(rows)} as const\n`)
console.log('photo credits', rows.length, 'landmarks →', out)
