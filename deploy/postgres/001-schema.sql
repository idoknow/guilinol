BEGIN;
CREATE FUNCTION unixepoch() RETURNS integer LANGUAGE sql STABLE AS $$
 SELECT floor(extract(epoch FROM statement_timestamp()))::integer
$$;
CREATE TABLE users (
  id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, nickname TEXT NOT NULL,
  salt TEXT NOT NULL, digest TEXT NOT NULL, verified INTEGER NOT NULL DEFAULT 0,
  failures INTEGER NOT NULL DEFAULT 0, locked_until INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE sessions (
  digest TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), expires INTEGER NOT NULL
);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE TABLE email_codes (
  email TEXT NOT NULL, purpose TEXT NOT NULL, digest TEXT NOT NULL, expires INTEGER NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(email,purpose)
);
CREATE TABLE mail_events (ip TEXT NOT NULL, email TEXT NOT NULL, sent INTEGER NOT NULL);
CREATE INDEX mail_ip ON mail_events(ip,sent);
CREATE INDEX mail_email ON mail_events(email,sent);
CREATE TABLE rate_limits (key TEXT PRIMARY KEY, until INTEGER NOT NULL, hits INTEGER NOT NULL);
CREATE TABLE feedback (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), kind TEXT NOT NULL,
 title TEXT NOT NULL, body TEXT NOT NULL, lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
 heading DOUBLE PRECISION, landmark_id TEXT, status TEXT NOT NULL DEFAULT 'draft',
 multica_issue TEXT, pr_url TEXT, submitted_at INTEGER,
 created_at INTEGER NOT NULL DEFAULT (unixepoch()), updated_at INTEGER NOT NULL DEFAULT (unixepoch())
);
CREATE INDEX feedback_quota ON feedback(user_id,submitted_at);
CREATE INDEX feedback_pending ON feedback(status,updated_at);
CREATE TABLE feedback_photos (
 feedback_id TEXT NOT NULL REFERENCES feedback(id), n INTEGER NOT NULL CHECK(n BETWEEN 1 AND 20),
 r2_key TEXT NOT NULL, bytes INTEGER NOT NULL, mime TEXT NOT NULL, view_label TEXT,
 exif_lat DOUBLE PRECISION, exif_lon DOUBLE PRECISION, exif_dir DOUBLE PRECISION, exif_time TEXT, ready INTEGER NOT NULL DEFAULT 0,
 uploaded_at INTEGER NOT NULL DEFAULT (unixepoch()), PRIMARY KEY(feedback_id,n)
);
CREATE TABLE feedback_upload_usage(user_id TEXT NOT NULL, uploaded_at INTEGER NOT NULL, bytes INTEGER NOT NULL);
CREATE INDEX upload_window ON feedback_upload_usage(user_id,uploaded_at);
CREATE INDEX upload_expiry ON feedback_upload_usage(uploaded_at);
CREATE FUNCTION record_upload_usage() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO feedback_upload_usage SELECT user_id,NEW.uploaded_at,NEW.bytes FROM feedback WHERE id=NEW.feedback_id;
 RETURN NEW;
END $$;
CREATE TRIGGER photo_usage AFTER INSERT OR UPDATE OF r2_key ON feedback_photos FOR EACH ROW EXECUTE FUNCTION record_upload_usage();
CREATE TABLE feedback_events (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, feedback_id TEXT NOT NULL REFERENCES feedback(id), status TEXT NOT NULL,
 message TEXT NOT NULL, screenshot_url TEXT, created_at INTEGER NOT NULL DEFAULT (unixepoch())
);
CREATE INDEX feedback_timeline ON feedback_events(feedback_id,id);
ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user','admin'));
ALTER TABLE users ADD COLUMN created_at INTEGER NOT NULL DEFAULT unixepoch();
ALTER TABLE feedback ADD COLUMN view_json TEXT;
ALTER TABLE feedback ADD COLUMN shot_state INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN notify_email INTEGER NOT NULL DEFAULT 1;
ALTER TABLE feedback ADD COLUMN admin_read_id INTEGER NOT NULL DEFAULT 0;
CREATE TABLE feedback_messages(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,feedback_id TEXT NOT NULL REFERENCES feedback(id) ON DELETE CASCADE,author_kind TEXT NOT NULL CHECK(author_kind IN ('user','admin','agent')),author_name TEXT NOT NULL,body TEXT NOT NULL,created_at INTEGER NOT NULL DEFAULT(unixepoch()),relayed_at INTEGER,source TEXT,UNIQUE(feedback_id,source));
CREATE INDEX feedback_chat ON feedback_messages(feedback_id,created_at,id);
CREATE TABLE feedback_mail(feedback_id TEXT PRIMARY KEY REFERENCES feedback(id) ON DELETE CASCADE, summary TEXT NOT NULL DEFAULT '', next_at INTEGER NOT NULL DEFAULT 0);
CREATE FUNCTION queue_feedback_mail() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE message_text text;
BEGIN
 IF TG_TABLE_NAME='feedback_events' THEN message_text=NEW.message; ELSE message_text=NEW.body; END IF;
 INSERT INTO feedback_mail(feedback_id,summary) VALUES(NEW.feedback_id,left(message_text,200))
 ON CONFLICT(feedback_id) DO UPDATE SET summary=right(trim(feedback_mail.summary||chr(10)||excluded.summary),200);
 RETURN NEW;
END $$;
CREATE TRIGGER notify_feedback_event AFTER INSERT ON feedback_events FOR EACH ROW EXECUTE FUNCTION queue_feedback_mail();
CREATE TRIGGER notify_feedback_message AFTER INSERT ON feedback_messages FOR EACH ROW WHEN (NEW.author_kind!='user') EXECUTE FUNCTION queue_feedback_mail();
ALTER TABLE users ADD COLUMN rowid INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE;
ALTER TABLE feedback ADD COLUMN rowid INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE;
COMMIT;
